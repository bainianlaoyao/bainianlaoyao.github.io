不是反教育；
不是反上升；
不是反专业；
他反的是把成功变成道德优越，把失败变成个人羞辱。
这个区分需要大量铺垫。我们一句话能说完，是因为我们已经进入了批判语境；但在公共论证中，这一步很难。
